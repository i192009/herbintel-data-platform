CREATE TABLE IF NOT EXISTS HERBINTEL.RAW.DATASET_MANIFESTS (
 PAYLOAD VARIANT NOT NULL, FILENAME VARCHAR NOT NULL, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
GRANT INSERT,SELECT ON TABLE HERBINTEL.RAW.DATASET_MANIFESTS TO ROLE HERBINTEL_LOADER;
GRANT SELECT ON TABLE HERBINTEL.RAW.DATASET_MANIFESTS TO ROLE HERBINTEL_TRANSFORMER;
