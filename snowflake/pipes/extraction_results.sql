CREATE PIPE IF NOT EXISTS HERBINTEL.RAW.PIPE_EXTRACTION_RESULTS AUTO_INGEST=TRUE AS
 COPY INTO HERBINTEL.RAW.EXTRACTION_RESULTS(payload,filename,loaded_at)
 FROM (SELECT PARSE_JSON($1:payload::string),METADATA$FILENAME,CURRENT_TIMESTAMP()
       FROM @HERBINTEL.RAW.HERBINTEL_S3/extraction_results/)
 FILE_FORMAT=(FORMAT_NAME=HERBINTEL.RAW.HERBINTEL_PARQUET) ON_ERROR=ABORT_STATEMENT;
GRANT MONITOR,OPERATE ON PIPE HERBINTEL.RAW.PIPE_EXTRACTION_RESULTS TO ROLE HERBINTEL_LOADER;
SHOW PIPES LIKE 'PIPE_EXTRACTION_RESULTS' IN SCHEMA HERBINTEL.RAW;
