CREATE PIPE IF NOT EXISTS HERBINTEL.RAW.PIPE_PROCESSING_RUNS AUTO_INGEST=TRUE AS
 COPY INTO HERBINTEL.RAW.PROCESSING_RUNS(payload,filename,loaded_at)
 FROM (SELECT PARSE_JSON($1:payload::string),METADATA$FILENAME,CURRENT_TIMESTAMP()
       FROM @HERBINTEL.RAW.HERBINTEL_S3/processing_runs/)
 FILE_FORMAT=(FORMAT_NAME=HERBINTEL.RAW.HERBINTEL_PARQUET) ON_ERROR=ABORT_STATEMENT;
GRANT MONITOR,OPERATE ON PIPE HERBINTEL.RAW.PIPE_PROCESSING_RUNS TO ROLE HERBINTEL_LOADER;
SHOW PIPES LIKE 'PIPE_PROCESSING_RUNS' IN SCHEMA HERBINTEL.RAW;
