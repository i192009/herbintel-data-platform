CREATE PIPE IF NOT EXISTS HERBINTEL.RAW.PIPE_DOCUMENT_METADATA AUTO_INGEST=TRUE AS
 COPY INTO HERBINTEL.RAW.DOCUMENT_METADATA(payload,filename,loaded_at)
 FROM (SELECT PARSE_JSON($1:payload::string),METADATA$FILENAME,CURRENT_TIMESTAMP()
       FROM @HERBINTEL.RAW.HERBINTEL_S3/document_metadata/)
 FILE_FORMAT=(FORMAT_NAME=HERBINTEL.RAW.HERBINTEL_PARQUET) ON_ERROR=ABORT_STATEMENT;
GRANT MONITOR,OPERATE ON PIPE HERBINTEL.RAW.PIPE_DOCUMENT_METADATA TO ROLE HERBINTEL_LOADER;
SHOW PIPES LIKE 'PIPE_DOCUMENT_METADATA' IN SCHEMA HERBINTEL.RAW;
