-- Replace only non-secret deployment values before execution.
CREATE STORAGE INTEGRATION IF NOT EXISTS HERBINTEL_S3_ACCESS
 TYPE=EXTERNAL_STAGE STORAGE_PROVIDER='S3' ENABLED=TRUE
 STORAGE_AWS_ROLE_ARN='${AWS_ROLE_ARN}'
 STORAGE_ALLOWED_LOCATIONS=('s3://${AWS_BUCKET}/warehouse/');
DESC INTEGRATION HERBINTEL_S3_ACCESS;
-- Use STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID returned above in AWS trust policy.
CREATE FILE FORMAT IF NOT EXISTS HERBINTEL.RAW.HERBINTEL_PARQUET TYPE=PARQUET;
CREATE STAGE IF NOT EXISTS HERBINTEL.RAW.HERBINTEL_S3
 URL='s3://${AWS_BUCKET}/warehouse/' STORAGE_INTEGRATION=HERBINTEL_S3_ACCESS
 FILE_FORMAT=HERBINTEL.RAW.HERBINTEL_PARQUET;
GRANT USAGE ON INTEGRATION HERBINTEL_S3_ACCESS TO ROLE HERBINTEL_LOADER;
GRANT USAGE ON STAGE HERBINTEL.RAW.HERBINTEL_S3 TO ROLE HERBINTEL_LOADER;
GRANT USAGE ON FILE FORMAT HERBINTEL.RAW.HERBINTEL_PARQUET TO ROLE HERBINTEL_LOADER;
