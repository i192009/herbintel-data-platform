-- Run as a provisioning administrator. No credentials belong in this file.
CREATE ROLE IF NOT EXISTS HERBINTEL_LOADER;
CREATE ROLE IF NOT EXISTS HERBINTEL_TRANSFORMER;
CREATE ROLE IF NOT EXISTS HERBINTEL_READER;
CREATE WAREHOUSE IF NOT EXISTS HERBINTEL_WH WAREHOUSE_SIZE='XSMALL'
 AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS HERBINTEL;
CREATE SCHEMA IF NOT EXISTS HERBINTEL.RAW;
CREATE SCHEMA IF NOT EXISTS HERBINTEL.STAGING;
CREATE SCHEMA IF NOT EXISTS HERBINTEL.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS HERBINTEL.MARTS;
CREATE SCHEMA IF NOT EXISTS HERBINTEL.AUDIT;
GRANT USAGE ON WAREHOUSE HERBINTEL_WH TO ROLE HERBINTEL_LOADER;
GRANT USAGE ON WAREHOUSE HERBINTEL_WH TO ROLE HERBINTEL_TRANSFORMER;
GRANT USAGE ON DATABASE HERBINTEL TO ROLE HERBINTEL_LOADER;
GRANT USAGE ON DATABASE HERBINTEL TO ROLE HERBINTEL_TRANSFORMER;
GRANT USAGE ON DATABASE HERBINTEL TO ROLE HERBINTEL_READER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE HERBINTEL TO ROLE HERBINTEL_TRANSFORMER;
GRANT USAGE ON SCHEMA HERBINTEL.RAW TO ROLE HERBINTEL_LOADER;
GRANT USAGE ON SCHEMA HERBINTEL.MARTS TO ROLE HERBINTEL_READER;
GRANT CREATE TABLE,CREATE VIEW ON SCHEMA HERBINTEL.STAGING TO ROLE HERBINTEL_TRANSFORMER;
GRANT CREATE TABLE,CREATE VIEW ON SCHEMA HERBINTEL.INTERMEDIATE TO ROLE HERBINTEL_TRANSFORMER;
GRANT CREATE TABLE,CREATE VIEW ON SCHEMA HERBINTEL.MARTS TO ROLE HERBINTEL_TRANSFORMER;
GRANT CREATE TABLE,CREATE VIEW ON SCHEMA HERBINTEL.AUDIT TO ROLE HERBINTEL_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA HERBINTEL.MARTS TO ROLE HERBINTEL_READER;
